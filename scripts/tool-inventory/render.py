#!/usr/bin/env python3
"""Render docs/platform/03-tool-inventory.md from the JSON the exporter prints.

    cargo run -q -p forge-worker -- catalog > /tmp/tools.json
    python3 scripts/tool-inventory/render.py /tmp/tools.json

Writes docs/platform/tool-inventory.json (full input schemas) and docs/platform/03-tool-inventory.md.
The "Platform policy" column is the PROPOSED hosted-mode rule (see 07-threat-model.md); it is
derived mechanically from each tool's declared Effects/Requires/toolset, not from runtime tests.
"""
import collections
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "platform"

ABBR = {
    "MUTATES_SESSION": "sess",
    "MUTATES_TARGET": "target",
    "WRITES_FILESYSTEM": "fs-write",
    "LAUNCHES_PROCESS": "process",
    "ACCESSES_NETWORK": "network",
    "CHANGES_UI_STATE": "ui",
    "MAY_DISCARD_DATA": "discard",
    "EXECUTES_FOREIGN_CODE": "foreign-code",
    "MUTATES_DEVICE": "device",
    "IDEMPOTENT": "idem",
    "CARRIES_TARGET_CONTENT": "target-content",
}

# Tools that change the host installation, open host windows, or manage plugins/agent-app
# registrations. In hosted mode they are disabled for tenants (operator-only or not offered).
HOST_ADMIN = {
    "engines_install", "engines_app_open", "settings_set", "plugins_refresh", "plugins_add",
    "plugins_remove", "project_open_folder", "setup_plan", "setup_apply", "setup_doctor",
    "setup_uninstall", "assets_key_set", "assets_key_remove",
}


def policy(t):
    req = t["requires"]
    eff = set(t["effects"])
    if t["id"] in HOST_ADMIN:
        return "operator-only"
    if req.startswith("os:") and "linux" not in req:
        return "unavailable (desktop OS)"
    if req == "engine:adb" or t["toolset"] == "frida":
        return "unavailable (needs local device)"
    if t["needs_consent"]:
        return "approval gate"
    if "ACCESSES_NETWORK" in eff or "LAUNCHES_PROCESS" in eff:
        return "editor, sandboxed worker"
    if t["read_only"]:
        return "viewer"
    return "editor"


def run_mode(t):
    eff = set(t["effects"])
    if "LAUNCHES_PROCESS" in eff or "ACCESSES_NETWORK" in eff or "EXECUTES_FOREIGN_CODE" in eff:
        return "job"
    return "sync"


def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def main():
    tools = json.load(open(sys.argv[1]))
    for t in tools:
        t["platform_policy"] = policy(t)
        t["run_mode"] = run_mode(t)
        t["output"] = "ToolOutput: evidence record (ev_ id) or {result: value}; no per-tool output schema"
    (OUT / "tool-inventory.json").write_text(json.dumps(tools, indent=2) + "\n")

    by_set = collections.defaultdict(list)
    for t in tools:
        by_set[t["toolset"]].append(t)
    pol = collections.Counter(t["platform_policy"] for t in tools)
    lines = [
        "# Tool inventory",
        "",
        "Generated by `forge-worker catalog` + `scripts/tool-inventory/render.py` from the live "
        "registry (`Engine::shared` with the AI and setup layer tools). Do not edit by hand.",
        "",
        f"- **{len(tools)} tools**: {sum(t['layer']=='engine' for t in tools)} engine tools "
        f"+ {sum(t['layer']!='engine' for t in tools)} AI/setup layer tools.",
        f"- Need consent at dispatch (`EXECUTES_FOREIGN_CODE` or `MUTATES_DEVICE`): "
        f"{sum(t['needs_consent'] for t in tools)}.",
        f"- Pure read-only (`IDEMPOTENT` only): {sum(t['read_only'] for t in tools)}.",
        f"- Available on this audit host with default settings: "
        f"{sum(t['available_here'] for t in tools)}. Reasons for the rest: "
        + "; ".join(f"{n}x {r.rstrip('.')}" for r, n in collections.Counter(
            t["unavailable_reason"] for t in tools if not t["available_here"]).most_common())
        + ". Default settings run in Clean room mode, which refuses tools that read a target's "
        "code, files or page source until Deep mode is enabled. The `Here` column reflects that.",
        "",
        "Proposed hosted-mode policy counts: "
        + ", ".join(f"{k}: {v}" for k, v in sorted(pol.items())) + ".",
        "",
        "## Columns",
        "",
        "- **Effects**: the tool's declared `Effects` bitflags (`crates/engine/src/tool.rs`). "
        "Abbreviations: " + ", ".join(f"`{v}`={k}" for k, v in ABBR.items()) + ".",
        "- **Requires**: `nothing`, `target` (an open target), `deep_engine` (Deep mode engine), "
        "`engine:<id>` (external program), `os:<list>`.",
        "- **Mode**: `sync` = in-process work, expected to finish in a request; `job` = launches a "
        "process or uses the network, so the API runs it as a queued job with streamed progress. "
        "Measured durations are not recorded yet; the Phase 5 adapter will collect them per call.",
        "- **Policy**: proposed permission in the hosted platform: `viewer`, `editor`, "
        "`editor, sandboxed worker`, `approval gate` (human approval, then `Consent::Granted`), "
        "`operator-only`, or `unavailable`.",
        "- **Output**: every tool returns `ToolOutput` (`kind: evidence` with the full evidence "
        "record, or `kind: value`). The engine defines no per-tool output schema; the evidence "
        "record schema is shared (`crates/evidence`).",
        "- **Input schema**: full JSON Schemas are in `tool-inventory.json` next to this file.",
        "- **Test status**: all engine crates' unit tests were run during the audit "
        "(see 00-audit-report.md). Per-tool live verification from upstream is in "
        "`docs/tool-status.md`. No tool has been exercised through the platform API yet.",
        "",
    ]
    for ts in sorted(by_set):
        lines += [f"## `{ts}` ({len(by_set[ts])})", "",
                  "| Tool | Title | Effects | Requires | Mode | Policy | Here |",
                  "|---|---|---|---|---|---|---|"]
        for t in by_set[ts]:
            eff = ", ".join(ABBR.get(e, e) for e in t["effects"]) or "none"
            here = "yes" if t["available_here"] else "no"
            lines.append(f"| `{t['id']}` | {esc(t['title'])} | {eff} | {t['requires']} | "
                         f"{t['run_mode']} | {t['platform_policy']} | {here} |")
        lines.append("")
    (OUT / "03-tool-inventory.md").write_text("\n".join(lines))
    print(f"wrote {len(tools)} tools")


if __name__ == "__main__":
    main()
